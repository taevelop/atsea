function cycle(base, changes, width) {
  const frames = [base, ...changes.map(change => base.map((line, i) => change[i] ?? line))];
  width = Math.max(width || 0, ...frames.flat().map(line => line.length));
  const normalized = frames.map(lines => lines.map(line => line.padEnd(width)));
  return [normalized[0], normalized[1], normalized[2], normalized[1]];
}
